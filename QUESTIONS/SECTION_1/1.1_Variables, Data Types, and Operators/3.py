# Explain with code when to use `int`, `float`, `str`, `bool`, and `None`.

# we use int() for storing integers
num = int(input("Enter a Number : "))
# anything inside the brakets of int are consider as integer

num1 = float(input("Enter a Number : "))
# anything inside the brakets of float are consider as float

word = str(input("Enter a Word : "))
# anything inside the brakets of str are consider as string

choice = bool(input("Enter True or False : "))
# anything inside the brakets of bool are consider as boolean

nothing = None
# nothing can store anything means null or void 

print(num)
print(num1)
print(word)
print(choice)
print(nothing)

print(type(num))
print(type(num1))
print(type(word))
print(type(choice))
print(type(nothing))
